#Python is a dynamically typed language
#A dynamically typed programming language is one in which the type of a variable is determined at runtime, rather than at compile time.
# This means you don't need to explicitly
# declare the type of a variable when you define it. Instead, the type is inferred based on the value assigned to the variable.

